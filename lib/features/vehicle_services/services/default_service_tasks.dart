// Rows to insert into `service_tasks` for a new request - one checklist per
// selected service type, concatenated (a booking can cover more than one
// kind of service in the same visit). `id` / `created_at` are generated by
// the database.
List<Map<String, dynamic>> defaultServiceTasks(
  String serviceRequestId,
  List<CarServiceType> types,
) {
  final seeds = <_SeedTask>[
    for (final type in types) ...(_byType[type.name] ?? _byType['general']!),
  ];
  return seeds
      .map((s) => {
            'service_request_id': serviceRequestId,
            'title': s.title,
            'detail': s.detail,
            'price': s.price,
            'is_extra': false,
            'approval': 'included',
          })
      .toList();
}
