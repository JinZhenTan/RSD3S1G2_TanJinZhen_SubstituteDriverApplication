import '../../../models/car_service_request.dart';

// Module 3: the checklist a car-service job starts with, seeded from the
// service type(s) the owner booked. Each entry becomes a row in
// `service_tasks` (is_extra = false, approval = 'included'). The staff ticks
// them off as they work, and anything extra they find on inspection is
// added later as a 'pending' task the owner must approve.
//
// Each type's own line items are set to sum to EXACTLY that type's fixed
// price (CarServiceType.price) - there is no separate transport/admin fee
// added on top, so the checklist's billable total always matches the
// estimate the owner was quoted at booking, with nothing appearing later
// that wasn't part of the original fixed price.

class _SeedTask {
  final String title;
  final String? detail;
  final double price;
  const _SeedTask(this.title, this.price, [this.detail]);
}

